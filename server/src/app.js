import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import pinoHttp from 'pino-http';
import { rateLimit } from 'express-rate-limit';
import { env } from './config/env.js';
import { errorHandler, notFoundHandler } from './middleware/errors.js';
import authRouter from './routes/auth.js';
import appointmentRouter from './routes/appointments.js';
import doctorRouter from './routes/doctors.js';
import dashboardRouter from './routes/dashboard.js';
import adminRouter from './routes/admin.js';

const app = express();
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({ origin: env.CLIENT_ORIGIN, credentials: true }));
app.use(express.json({ limit: '1mb' }));
app.use(cookieParser());
app.use(pinoHttp({ enabled: env.NODE_ENV !== 'test', redact: ['req.headers.authorization', 'req.headers.cookie', 'req.body.password'] }));
app.get('/api/v1/health', (_req, res) => res.json({ success: true, data: { status: 'ok' } }));
app.use('/api/v1/auth/login', rateLimit({ windowMs: env.LOGIN_RATE_LIMIT_WINDOW_MS, limit: env.LOGIN_RATE_LIMIT_MAX, standardHeaders: true, legacyHeaders: false, handler: (_req, res) => res.status(429).json({ success: false, error: { code: 'RATE_LIMITED', message: 'Too many login attempts. Try again later.' } }) }));
app.use('/api/v1/auth', authRouter);
app.use('/api/v1/appointments', appointmentRouter);
app.use('/api/v1/doctors', doctorRouter);
app.use('/api/v1/dashboard', dashboardRouter);
app.use('/api/v1/admin', adminRouter);
app.use(notFoundHandler);
app.use(errorHandler);
export default app;
